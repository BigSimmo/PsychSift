#!/usr/bin/env bash

set -Eeuo pipefail

fail() {
  printf '[codex-cloud:shims] ERROR: %s\n' "$*" >&2
  exit 1
}

repo_root="$(git rev-parse --show-toplevel 2>/dev/null)" || fail "Run this script from the PsychSift repository."
cd "$repo_root"
repo_root="$(pwd -P)"

# The documented launcher-name exception may use an existing generated profile;
# unexpected provider names must never be hidden by sourcing that profile.
if bash --noprofile --norc scripts/check-codex-cloud-raw-env.sh; then
  :
else
  raw_boundary_status="$?"
  case "$raw_boundary_status" in
    2) ;; # Restricted continuation; the raw boundary remains failed.
    *) exit "$raw_boundary_status" ;;
  esac
fi

expected_node_major="$(tr -cd '0-9' < .node-version)"
[[ -n "$expected_node_major" ]] || fail "Could not read the Node major from .node-version."

expected_npm_major="$(sed -n 's/.*"npm"[[:space:]]*:[[:space:]]*"\([0-9][0-9]*\)\.x".*/\1/p' package.json | head -n 1)"
[[ -n "$expected_npm_major" ]] || fail "Could not read the npm major from package.json engines.npm."

runtime_profile="$HOME/.clinical-kb-codex-cloud.sh"
[[ -f "$runtime_profile" ]] || fail "The generated Cloud runtime profile is unavailable; run setup first."
if grep -q '^# PsychSift checkout: ' "$runtime_profile"; then
  grep -Fqx "# PsychSift checkout: $repo_root" "$runtime_profile" ||
    fail "The generated runtime profile belongs to another checkout; use an isolated HOME and CODEX_HOME."
fi
# shellcheck source=scripts/lib/codex-cloud-paths.sh
source scripts/lib/codex-cloud-paths.sh

# shellcheck source=/dev/null
source "$runtime_profile"

shim_dir="$HOME/.local/bin"
[[ ! -L "$shim_dir" ]] || fail "The command-shim directory must not be a symbolic link."
mkdir -p "$HOME/.local/bin"
shim_dir="$(cd "$shim_dir" && pwd -P)"

node_version_supported() {
  local version="$1"
  local actual_major actual_minor actual_patch
  [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 1
  IFS=. read -r actual_major actual_minor actual_patch <<< "$version"
  (( actual_major == 24 )) || return 1
  (( actual_minor > 15 )) && return 0
  (( actual_minor == 15 && actual_patch >= 0 ))
}

# Existing shims must never be picked as their own targets, so every PATH lookup below skips
# $HOME/.local/bin.
fallback_path=""
path_entry_seen=false
IFS=: read -r -a path_entries <<< "$PATH"
for path_entry in "${path_entries[@]}"; do
  [[ "$path_entry" == "$HOME/.local/bin" ]] && continue
  [[ -n "$path_entry" && "$path_entry" -ef "$shim_dir" ]] && continue
  if $path_entry_seen; then
    fallback_path+=:
  fi
  fallback_path+="$path_entry"
  path_entry_seen=true
done
unset path_entries path_entry path_entry_seen

resolved_node_version=""
if command -v nvm >/dev/null 2>&1; then
  resolved_node_version="$(nvm version "$expected_node_major" 2>/dev/null || true)"
fi
if [[ -n "$resolved_node_version" && "$resolved_node_version" != "N/A" ]]; then
  node_bin="$NVM_DIR/versions/node/$resolved_node_version/bin"
else
  fallback_node="$(PATH="$fallback_path" command -v node 2>/dev/null || true)"
  [[ -n "$fallback_node" ]] || fail "Node ${expected_node_major} is unavailable through nvm or PATH."
  node_bin="$(cd "$(dirname "$fallback_node")" && pwd)"
fi
node_bin="$(cd "$node_bin" && pwd -P)"
[[ "$node_bin" != "$shim_dir" ]] || fail "The selected runtime must be outside the command-shim directory."
command_paths=()
# Resolve every command and validate every destination before replacing any of
# them. Atomic rename replaces a destination symlink itself, never its target.
for command_name in node npm npx; do
  if [[ "$command_name" = node ]]; then
    command_path="$node_bin/node"
  else
    command_path=""
    if [[ -x "$node_bin/$command_name" ]]; then
      command_path="$node_bin/$command_name"
    else
      command_path="$(PATH="$fallback_path" command -v "$command_name" 2>/dev/null || true)"
    fi
  fi
  [[ -f "$command_path" && -x "$command_path" ]] || fail "${command_name} is unavailable in Node ${expected_node_major}; a regular executable is required."
  resolved_command="$(readlink -f "$command_path")" || fail "Could not resolve ${command_name}."
  case "$resolved_command" in
    "$shim_dir"/*) fail "The selected ${command_name} target resolves into the command-shim directory." ;;
  esac
  if grep -Fq '# Generated by scripts/install-codex-cloud-command-shims.sh.' "$command_path"; then
    fail "The selected ${command_name} target is itself a generated command shim."
  fi
  destination="$shim_dir/$command_name"
  if [[ -e "$destination" && ! -L "$destination" ]]; then
    [[ -f "$destination" ]] || fail "The ${command_name} destination must be a file or symbolic link."
    grep -Fq '# Generated by scripts/install-codex-cloud-command-shims.sh.' "$destination" ||
      fail "The ${command_name} destination is unmanaged; preserve it and use an isolated HOME."
    if grep -q '^# PsychSift checkout: ' "$destination"; then
      grep -Fqx "# PsychSift checkout: $repo_root" "$destination" ||
        fail "The ${command_name} destination belongs to another checkout."
    fi
  fi
  # Pin the resolved executable, so an intermediate symlink cannot start
  # pointing back through a newly replaced destination after installation.
  command_paths+=("$resolved_command")
done
node_version="$("${command_paths[0]}" -p 'process.versions.node' 2>/dev/null || true)"
node_version_supported "$node_version" || fail "Node ${expected_node_major}.x >=24.15.0 and <25 is required; detected ${node_version:-unavailable}."
for command_index in 1 2; do
  command_path="${command_paths[$command_index]}"
  if [[ "$command_path" != "$node_bin/"* ]]; then
    fallback_tool_version="$("$command_path" --version 2>/dev/null | grep -Eo '[0-9]+\.[0-9]+\.[0-9]+' | head -n 1 || true)"
    [[ "${fallback_tool_version%%.*}" = "$expected_npm_major" ]] ||
      fail "${command_path##*/} ${expected_npm_major}.x is required (package.json engines.npm); the PATH fallback is ${fallback_tool_version:-unavailable}."
  fi
done

quoted_checkout="$(codex_cloud_shell_quote "$repo_root")"
quoted_runtime_profile="$(codex_cloud_shell_quote "$runtime_profile")"
quoted_node_bin="$(codex_cloud_shell_quote "$node_bin")"
candidates=()
trap 'if (( ${#candidates[@]} )); then rm -f -- "${candidates[@]}"; fi' EXIT
command_index=0
for command_name in node npm npx; do
  command_path="${command_paths[$command_index]}"
  quoted_command_path="$(codex_cloud_shell_quote "$command_path")"
  candidate="$(mktemp "$shim_dir/.codex-cloud-${command_name}.XXXXXX")"
  candidates+=("$candidate")
  cat > "$candidate" <<EOF
#!/usr/bin/env bash
set -Eeuo pipefail
# Generated by scripts/install-codex-cloud-command-shims.sh. Re-running setup
# PsychSift checkout: $repo_root
# or maintenance replaces this wrapper through the same idempotent command.
clean_path=""
path_entry_seen=false
IFS=: read -r -a path_entries <<< "\$PATH"
for path_entry in "\${path_entries[@]}"; do
  [[ "\$path_entry" == "\$HOME/.local/bin" ]] && continue
  [[ -n "\$path_entry" && "\$path_entry" -ef "\$HOME/.local/bin" ]] && continue
  if \$path_entry_seen; then
    clean_path+=:
  fi
  clean_path+="\$path_entry"
  path_entry_seen=true
done
unset path_entries path_entry path_entry_seen
if [[ "\$(git rev-parse --show-toplevel 2>/dev/null || true)" != $quoted_checkout ]]; then
  # Preserve an unrelated checkout's environment and its own PATH runtime.
  export PATH="\$clean_path"
  fallback_command="\$(command -v $command_name || true)"
  [[ -n "\$fallback_command" ]] || { printf '[codex-cloud:shims] No external $command_name on PATH.\\n' >&2; exit 127; }
  exec "\$fallback_command" "\$@"
fi
. $quoted_runtime_profile
if [[ -n "\$clean_path" ]]; then
  export PATH=$quoted_node_bin:"\$clean_path"
else
  export PATH=$quoted_node_bin
fi
unset clean_path
exec $quoted_command_path "\$@"
EOF
  chmod 0755 "$candidate"
  command_index=$((command_index + 1))
done
command_index=0
for command_name in node npm npx; do
  mv -fT -- "${candidates[$command_index]}" "$shim_dir/$command_name"
  command_index=$((command_index + 1))
done
trap - EXIT

printf '[codex-cloud:shims] PASS: node, npm, and npx load the generated Cloud profile.\n'
