// Generates src/data/therapies-index.json — a trimmed, server-importable projection
// of src/data/therapies-source.json (~2.5 MB). The full dataset is fetched
// client-side by the interactive Therapy Compass screens; the server only needs a small
// rankable/metadata projection for routing (generateStaticParams / notFound / metadata)
// and the universal-search "therapies" domain. Re-run after editing the source dataset,
// then run Prettier (which owns the committed file's exact formatting):
//
//   node scripts/build-therapies-index.mjs && npm run format
//
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { escapeFalseOpenAiKeySignatures } from "./lib/escape-false-openai-key-signatures.mjs";
import {
  THERAPY_GENERATED_PATHS,
  THERAPY_HASHED_ASSET_RE,
  assertValidTherapyReviewRecords,
} from "./lib/therapy-review-contract.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicData = join(root, THERAPY_GENERATED_PATHS.publicDirectory);
const serverTarget = join(root, THERAPY_GENERATED_PATHS.serverIndex);
const manifestTarget = join(root, THERAPY_GENERATED_PATHS.manifest);
const checkOnly = process.argv.includes("--check");
// --revoke-previous: retire the retained previous generation instead of rotating
// it in. Use when the replaced generation must not keep being served (e.g. it
// carries sign-offs that were revoked). Pre-deploy bundles then 404 on the old
// hashed URL and `useTherapyData` falls back to the unversioned alias, which
// holds the current data.
const revokePrevious = process.argv.includes("--revoke-previous");
const currentManifest = existsSync(manifestTarget) ? readFileSync(manifestTarget, "utf8") : "";
// The hand-edited source catalogue, deliberately OUTSIDE `publicData` — this
// generator writes every file in that directory, and until 2026-08-12 the
// source was `public/therapy-compass-data/therapies.json`, which it also wrote
// as `legacyFullTarget`. Source and target being one file meant each run
// consumed its own output: `curatedFull` nulls every tag-echo `modality`
// (see curatedModality), so the first run overwrote the author's raw values
// with the scrubbed ones and every later run re-read the scrubbed copy. It
// survived only because the scrub is idempotent — the raw input was still
// destroyed, recoverable from git history alone. Keep this path out of
// `publicData` so a re-run can never consume what it just wrote.
const source = join(root, THERAPY_GENERATED_PATHS.source);
if (!existsSync(source)) {
  throw new Error(`Missing therapy source dataset. Expected ${source}.`);
}

const therapies = JSON.parse(readFileSync(source, "utf8"));

// Review status is clinical governance, not display metadata. Validate the
// canonical source before any derived file is checked, written, or pruned so a
// bare `reviewStatus: "reviewed"` edit can never publish without all seven
// explicit checks, public-safe attribution, timestamp, and content-bound hash.
assertValidTherapyReviewRecords(therapies);

const CATALOGUE_KINDS = ["full", "index"];
const RETIRED_HOME_ALIAS = THERAPY_GENERATED_PATHS.retiredHomeAlias;

/**
 * Content-addressed catalogue assets this generator owns. Keep matching the
 * retired `therapies-home.*.json` stem so generation prunes it and check mode
 * refuses any copy that reappears instead of letting obsolete payloads hide.
 */
const HASHED_ASSET_RE = THERAPY_HASHED_ASSET_RE;

/** Every hashed catalogue asset currently sitting in `public/therapy-compass-data`. */
function listHashedAssets() {
  return readdirSync(publicData)
    .filter((name) => HASHED_ASSET_RE.test(name))
    .sort();
}

/**
 * Extract the interior of `name = { ... } as const` so a nested `}` (or a
 * string containing `}`) cannot truncate the parse the way `[^}]*` did and
 * make staleness comparisons pass vacuously on trailing fields. The generator
 * always terminates these objects with `} as const`.
 */
function extractConstObjectBody(source, name) {
  return source.match(new RegExp(`${name} = \\{([\\s\\S]*?)\\} as const`))?.[1] ?? "";
}

/**
 * Filenames recorded under `name` in a `generated-assets.ts` body, keyed by
 * kind. Keyed rather than positional: a manifest missing one kind must not
 * shift the others into the wrong slot.
 */
function manifestAssets(body, name) {
  const block = extractConstObjectBody(body, name);
  const entries = CATALOGUE_KINDS.map((kind) => [kind, block.match(new RegExp(`${kind}: "([^"]+)"`))?.[1]]).filter(
    ([, filename]) => Boolean(filename),
  );
  return Object.fromEntries(entries);
}

function renderManifest(current, previous, summary) {
  const entry = (assets) => `{\n  full: "${assets.full}",\n  index: "${assets.index}",\n} as const;\n`;
  return [
    "// Generated by scripts/build-therapies-index.mjs. Do not edit.",
    `export const THERAPY_CATALOGUE_ASSETS = ${entry(current)}`,
    "// The generation this one replaced. Retained on disk across one content-",
    "// changing regeneration so a client whose bundle still names the previous",
    "// content-addressed URL does not 404 mid-session; older generations are",
    "// pruned. `useTherapyData` also falls back to the unversioned alias for",
    "// bundles that include that fallback (pre-fallback clients are best-effort).",
    `export const THERAPY_CATALOGUE_ASSETS_PREVIOUS = ${entry(previous)}`,
    "// First-paint metadata for the Therapy home. The landing page renders only",
    "// the catalogue count and trusted default artifact destinations, so it must",
    "// not download and parse a record projection before its LCP can paint.",
    "export const THERAPY_CATALOGUE_SUMMARY = {",
    `  totalCount: ${summary.totalCount},`,
    `  needsReviewCount: ${summary.needsReviewCount},`,
    `  defaultBriefSlug: ${JSON.stringify(summary.defaultBriefSlug)},`,
    `  defaultSheetSlug: ${JSON.stringify(summary.defaultSheetSlug)},`,
    "} as const;\n",
  ].join("\n");
}

// Detail and recommend load the full catalogue (`catalogue: "full"`), not the
// index projections. Strip dead modality field from full catalogue outputs.
const curatedFull = therapies.map((therapy) => {
  const item = { ...therapy };
  delete item.modality;
  return item;
});

const projected = therapies
  .map((t) => ({
    slug: t.slug,
    name: t.name,
    category: t.category ?? null,
    clinicalSummary: t.clinicalSummary ?? null,
    bestUsedFor: t.bestUsedFor ?? null,
    targetSymptoms: t.targetSymptoms ?? null,
    indications: t.indications ?? null,
    reviewStatus: t.reviewStatus ?? "needs_review",
    patientSheetAvailable: Boolean(t.patientSheetAvailable),
    briefInterventionAvailable: Boolean(t.briefInterventionAvailable),
    tags: Array.isArray(t.tags) ? t.tags : [],
    aliases: Array.isArray(t.aliases) ? t.aliases : [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const browserProjected = therapies
  .map((therapy) => ({
    slug: therapy.slug,
    name: therapy.name,
    category: therapy.category ?? null,
    // The browser index is the browse/pathway payload, not the search corpus.
    // Keep only the short subtitle the catalogue cards render. Search loads the
    // full records so removing long clinical prose here cannot change recall.
    bestUsedFor: therapy.bestUsedFor?.split(/(?<=\.)\s+/)[0] ?? null,
    reviewStatus: therapy.reviewStatus ?? "needs_review",
    patientSheetAvailable: Boolean(therapy.patientSheetAvailable),
    briefInterventionAvailable: Boolean(therapy.briefInterventionAvailable),
    tags: Array.isArray(therapy.tags) ? therapy.tags : [],
    aliases: Array.isArray(therapy.aliases) ? therapy.aliases : [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const catalogueSummary = {
  totalCount: browserProjected.length,
  // Records still awaiting qualified-clinician sign-off. Therapy ships its review
  // state rather than hiding unreviewed records, so the library notice states this
  // count; computing it here keeps the notice from drifting away from the data.
  needsReviewCount: browserProjected.filter((therapy) => therapy.reviewStatus !== "reviewed").length,
  defaultBriefSlug: browserProjected.find((therapy) => therapy.briefInterventionAvailable)?.slug ?? null,
  defaultSheetSlug: browserProjected.find((therapy) => therapy.patientSheetAvailable)?.slug ?? null,
};

if (checkOnly) {
  const summaryBlock = extractConstObjectBody(currentManifest, "THERAPY_CATALOGUE_SUMMARY");
  const recordedSummary = {
    totalCount: Number(summaryBlock.match(/totalCount: (\d+)/)?.[1] ?? Number.NaN),
    needsReviewCount: Number(summaryBlock.match(/needsReviewCount: (\d+)/)?.[1] ?? Number.NaN),
    defaultBriefSlug: summaryBlock.match(/defaultBriefSlug: (null|"[^"]+")/)?.[1] ?? "",
    defaultSheetSlug: summaryBlock.match(/defaultSheetSlug: (null|"[^"]+")/)?.[1] ?? "",
  };
  if (
    recordedSummary.totalCount !== catalogueSummary.totalCount ||
    recordedSummary.needsReviewCount !== catalogueSummary.needsReviewCount ||
    recordedSummary.defaultBriefSlug !== JSON.stringify(catalogueSummary.defaultBriefSlug) ||
    recordedSummary.defaultSheetSlug !== JSON.stringify(catalogueSummary.defaultSheetSlug)
  ) {
    throw new Error("Generated therapy catalogue summary is stale. Re-run `node scripts/build-therapies-index.mjs`.");
  }
}

/**
 * Exact bytes of a pretty projection asset. Shared by `syncTarget` and the
 * content-addressed writer so a hashed asset is byte-identical to what the
 * server-side projection would have written — the hash must not depend on which
 * code path produced it.
 */
function projectionBytes(records) {
  return `${escapeFalseOpenAiKeySignatures(JSON.stringify(records, null, 2))}\n`;
}

/**
 * Exact bytes of the full catalogue: compact single-line JSON (no pretty indent,
 * no trailing newline) — the historical `therapies.json` shape (~2.5 MB on one
 * line). Pretty-printing it turns a modality scrub into a ~36k-line PR churn
 * (`#179`). Projections stay pretty via `projectionBytes`/`syncTarget`.
 */
function fullCatalogueBytes(records) {
  return escapeFalseOpenAiKeySignatures(JSON.stringify(records));
}

function syncTarget(target, records) {
  const expected = projectionBytes(records);
  if (checkOnly) {
    let actual = "";
    try {
      actual = readFileSync(target, "utf8");
    } catch {
      throw new Error(`Missing generated therapy index: ${target}`);
    }
    let parsed;
    try {
      parsed = JSON.parse(actual);
    } catch {
      throw new Error(`Generated therapy index is invalid JSON: ${target}`);
    }
    if (JSON.stringify(parsed) !== JSON.stringify(records)) {
      throw new Error(`Generated therapy index is stale: ${target}`);
    }
    return;
  }
  writeFileSync(target, expected);
  console.log(`Wrote ${records.length} therapy records to ${target}`);
}

syncTarget(serverTarget, projected);
if (!checkOnly) {
  // Content-addressed assets are the ONLY catalogue payloads written to
  // `publicData`. The unversioned aliases (`therapies.json` and
  // `therapies-index.json`) used to be written here too,
  // byte-identical to their hashed twin, which cost a second copy of every
  // payload in the working tree and in every Docker image — 2.66 MB, and 5.33 MB
  // during the one-deploy grace window. They are now served by a rewrite in
  // next.config.ts that points each alias path at the current hashed filename,
  // so the alias URLs behave exactly as before with no duplicated bytes.
  //
  // The alias URLs themselves are NOT optional: `useTherapyData` falls back to
  // them when a bundle older than the grace generation names a hashed file that
  // no longer exists. A rewrite preserves that contract; deleting the aliases
  // outright would not.
  const hashedAsset = (contents, stem) => {
    const buffer = Buffer.from(contents);
    const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 16);
    const filename = `${stem}.${hash}.json`;
    writeFileSync(join(publicData, filename), buffer);
    return filename;
  };
  // Write the curated full catalogue (not a raw source copy): detail/recommend
  // fetch this payload, and tag-echo modalities must not survive on that path.
  // Keep the payload compact — see fullCatalogueBytes.
  const fullFilename = hashedAsset(fullCatalogueBytes(curatedFull), "therapies");
  const indexFilename = hashedAsset(projectionBytes(browserProjected), "therapies-index");
  const current = { full: fullFilename, index: indexFilename };
  // The generation being replaced stays on disk across one content-changing
  // regeneration. A client loaded before that regeneration has the *previous*
  // hashed URL compiled into its bundle, and pruning it immediately would 404
  // that session the moment it opened a catalogue route — the
  // deployment-straddling failure the unversioned aliases were added to
  // prevent, reintroduced one level down.
  const priorCurrent = manifestAssets(currentManifest, "THERAPY_CATALOGUE_ASSETS");
  const priorPrevious = manifestAssets(currentManifest, "THERAPY_CATALOGUE_ASSETS_PREVIOUS");
  // Rotate the grace window per kind, and only when that kind's content actually
  // changed. Rotating on every invocation would make a second local re-run —
  // routine while iterating — silently retire the generation a client loaded
  // before the last deploy still fetches, which is the whole point of retaining
  // it. A kind absent from the old manifest (first run, hand-edited file) falls
  // back to the new filename so the retained set never names a file that was
  // never written.
  const previous = Object.fromEntries(
    CATALOGUE_KINDS.map((kind) => {
      if (revokePrevious) return [kind, current[kind]];
      const replaced = priorCurrent[kind];
      if (replaced && replaced !== current[kind]) return [kind, replaced];
      return [kind, priorPrevious[kind] ?? current[kind]];
    }),
  );
  writeFileSync(manifestTarget, renderManifest(current, previous, catalogueSummary));
  // Prune everything older than those two generations. Without this, every data
  // revision strands the previous full catalogue (~2.5 MB) plus the browse projection
  // in `public/` forever — carried in git history and in every Docker image. PR
  // #1489 stranded two inside a single pull request and needed a hand-deletion
  // commit to clear them. Growth is now bounded at two generations, not N.
  const keep = new Set([...Object.values(current), ...Object.values(previous)]);
  const pruned = listHashedAssets().filter((name) => !keep.has(name));
  for (const name of pruned) rmSync(join(publicData, name));
  const retiredHomeAliasPath = join(publicData, RETIRED_HOME_ALIAS);
  if (existsSync(retiredHomeAliasPath)) {
    rmSync(retiredHomeAliasPath);
    console.log(`Pruned retired therapy alias: ${RETIRED_HOME_ALIAS}`);
  }
  console.log(`Wrote content-addressed therapy assets: ${indexFilename}, ${fullFilename}`);
  if (pruned.length > 0) console.log(`Pruned ${pruned.length} superseded asset(s): ${pruned.join(", ")}`);
} else {
  if (!existsSync(manifestTarget)) {
    throw new Error(`Missing generated therapy asset manifest: ${manifestTarget}`);
  }
  if (existsSync(join(publicData, RETIRED_HOME_ALIAS))) {
    throw new Error(
      `Retired Therapy home alias is still committed: ${RETIRED_HOME_ALIAS}. Re-run \`node scripts/build-therapies-index.mjs\` to prune it.`,
    );
  }
  const manifest = readFileSync(manifestTarget, "utf8");
  // Only the current generation and the one-deploy grace generation may be
  // committed. This is the gate that would have caught the orphans PR #1489
  // stranded before review did, and it keeps the retained set explicit rather
  // than letting each regeneration quietly add another 2.5 MB to the image.
  const manifested = new Set([
    ...Object.values(manifestAssets(manifest, "THERAPY_CATALOGUE_ASSETS")),
    ...Object.values(manifestAssets(manifest, "THERAPY_CATALOGUE_ASSETS_PREVIOUS")),
  ]);
  const orphaned = listHashedAssets().filter((name) => !manifested.has(name));
  if (orphaned.length > 0) {
    throw new Error(
      `Superseded therapy assets are still committed: ${orphaned.join(", ")}. Re-run \`node scripts/build-therapies-index.mjs\` to prune them.`,
    );
  }
  for (const retained of Object.values(manifestAssets(manifest, "THERAPY_CATALOGUE_ASSETS_PREVIOUS"))) {
    if (!existsSync(join(publicData, retained))) {
      throw new Error(
        `Retained previous-generation therapy asset is missing: ${retained}. Clients loaded before the last deploy fetch this URL.`,
      );
    }
  }
  for (const [kind, records] of [
    ["full", curatedFull],
    ["index", browserProjected],
  ]) {
    const filename = manifest.match(new RegExp(`${kind}: "([^"]+)"`))?.[1];
    if (!filename) throw new Error(`Missing ${kind} therapy asset in ${manifestTarget}`);
    const contents = readFileSync(join(publicData, filename));
    const hash = createHash("sha256").update(contents).digest("hex").slice(0, 16);
    const stem = kind === "full" ? "therapies" : `therapies-${kind}`;
    if (filename !== `${stem}.${hash}.json` || JSON.stringify(JSON.parse(contents)) !== JSON.stringify(records)) {
      throw new Error(`Generated therapy asset is stale: ${filename}`);
    }
    // The unversioned alias must NOT exist as a file: it is served by a rewrite
    // in next.config.ts pointing at the hashed asset above. A file here would
    // shadow nothing (afterFiles rewrites run only when no static file matched),
    // so it would silently go stale the next time the catalogue regenerated —
    // exactly the duplicated-bytes state this replaced.
    const legacyFilename = `${stem}.json`;
    if (existsSync(join(publicData, legacyFilename))) {
      throw new Error(
        `Therapy alias ${legacyFilename} is a duplicate file. The alias is served by the next.config.ts rewrite; delete the file.`,
      );
    }
    const text = contents.toString("utf8");
    const expected = kind === "full" ? fullCatalogueBytes(records) : projectionBytes(records);
    if (text !== expected) {
      throw new Error(`Generated therapy asset does not match its canonical bytes: ${filename}`);
    }
    if (kind === "full" && text.includes("\n")) {
      throw new Error(`Full therapy catalogue must stay compact single-line JSON (no pretty-print): ${filename}`);
    }
  }
}
if (checkOnly) console.log(`Therapy indexes are current (${projected.length} records).`);
