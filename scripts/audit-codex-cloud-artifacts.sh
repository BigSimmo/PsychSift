#!/usr/bin/env bash

set -Eeuo pipefail

# Read-only retirement inventory. Never source a profile, execute a runtime,
# rewrite a startup file, or remove an artifact based on a marker alone.
if [[ "$#" != 0 && ( "$#" != 1 || "$1" != --dry-run ) ]]; then
  printf 'Usage: bash scripts/audit-codex-cloud-artifacts.sh [--dry-run]\n' >&2
  exit 2
fi
repo_root="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 1
cd "$repo_root"
repo_root="$(pwd -P)"
# shellcheck source=scripts/lib/codex-cloud-paths.sh
source scripts/lib/codex-cloud-paths.sh

report_file() {
  local artifact="$1" marker="$2" state=missing digest=none
  if [[ -L "$artifact" ]]; then
    state=symlink-preserve
  elif [[ -f "$artifact" ]]; then
    state=unmanaged-preserve
    if grep -Fq "$marker" "$artifact"; then
      state=managed-marker-review
      digest="$(sha256sum "$artifact" | awk '{print $1}')"
      if grep -q '^# PsychSift checkout: ' "$artifact" &&
        ! grep -Fqx "# PsychSift checkout: $repo_root" "$artifact"; then
        state=other-checkout-preserve
      fi
    fi
  elif [[ -e "$artifact" ]]; then
    state=non-file-preserve
  fi
  printf '[codex-cloud:artifacts] %s sha256=%s path=%s\n' "$state" "$digest" "$artifact"
}

printf '[codex-cloud:artifacts] DRY-RUN only; markers and hashes are evidence for review, not deletion authority.\n'
report_file "$HOME/.clinical-kb-codex-cloud.sh" '# Generated by scripts/setup-codex-cloud.sh.'
for command_name in node npm npx; do
  report_file "$HOME/.local/bin/$command_name" '# Generated by scripts/install-codex-cloud-command-shims.sh.'
done
for shell_profile in "$HOME/.bashrc" "$HOME/.profile" "$HOME/.bash_profile"; do
  report_file "$shell_profile" '# PsychSift Codex Cloud runtime'
done
report_file "${CODEX_HOME:-$HOME/.codex}/config.toml" '# BEGIN clinical-kb-codex-cloud shell policy (managed by setup-codex-cloud.sh)'
checkout_key="$(codex_cloud_checkout_key "$repo_root")"
report_file "$HOME/.cache/clinical-kb-codex/checkouts/$checkout_key/cloud-expected-base-sha" 'not-a-managed-file-marker'
report_file "$HOME/.cache/clinical-kb-codex/cloud-expected-base-sha" 'not-a-managed-file-marker'
printf '[codex-cloud:artifacts] No files changed. Preserve host edits; retire reviewed managed blocks separately.\n'
